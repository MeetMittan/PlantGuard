import { readFileSync } from 'node:fs';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import { screen, waitFor } from '@testing-library/react';
import { modelManager } from '@/ai/model-manager/model-manager';
import { DemoVisionProvider } from '@/ai/providers/demo-provider';
import { ModelRuntimeError } from '@/ai/utils/errors';
import { db } from '@/db/database';
import { createPlant } from '@/db/repositories/plants';
import { renderApp } from '@/test/render';
import { resetDatabase } from '@/test/db-helpers';
import { testProvider } from '@/test/mock-model-manager';

vi.mock('@/ai/model-manager/model-manager', async (orig) => (await import('@/test/mock-model-manager')).modelManagerMockFactory(orig));
vi.mock('@/services/image-processing/image-processing', async (orig) =>
  (await import('@/test/mock-model-manager')).imageProcessingMockFactory(orig),
);

const leaf = () => new File([readFileSync('tests/fixtures/tomato-early-blight.jpg')], 'leaf.jpg', { type: 'image/jpeg' });

async function readyModel() {
  testProvider.current = new DemoVisionProvider();
  await modelManager.refresh();
  await modelManager.download();
}

beforeEach(async () => {
  await resetDatabase();
  testProvider.current = new DemoVisionProvider();
});

afterEach(() => {
  Object.defineProperty(navigator, 'mediaDevices', { configurable: true, value: undefined });
  vi.restoreAllMocks();
});

async function analyseLeaf(user: Awaited<ReturnType<typeof renderApp>>['user']) {
  await user.upload(await screen.findByTestId('photo-input'), leaf());
  await user.click(await screen.findByRole('button', { name: /analyse on this device/i }));
  await screen.findByText('What the model observed');
}

describe('ScannerPage', () => {
  it('offers download and save-without-analysis when the model is unavailable', async () => {
    await modelManager.deleteCachedModel();
    const { user } = await renderApp('/scan');
    await user.upload(await screen.findByTestId('photo-input'), leaf());
    expect(await screen.findByRole('heading', { name: /save without analysis/i })).toBeInTheDocument();
    expect(screen.queryByRole('button', { name: /analyse/i })).not.toBeInTheDocument();
    expect(screen.getAllByRole('button', { name: /download ai model/i }).length).toBeGreaterThan(0);
  });

  it('separates observations from explanations and saves observation + assessment together', async () => {
    await readyModel();
    const { user } = await renderApp('/scan');
    await analyseLeaf(user);

    expect(screen.getAllByText('Possible issue').length).toBeGreaterThan(0);
    expect(screen.getByText('Brown or dark spots')).toBeInTheDocument();
    expect(screen.getByText('Possible explanations')).toBeInTheDocument();
    expect(screen.getByText('Early blight')).toBeInTheDocument();
    expect(screen.getAllByText('Suggested by the AI model').length).toBe(1);
    expect(screen.getAllByText('From reference library').length).toBeGreaterThan(0);
    expect(screen.getByText(/not generated by the AI/i)).toBeInTheDocument();

    await user.click(screen.getByRole('button', { name: /save observation/i }));
    expect(await screen.findByRole('heading', { name: /observation saved/i })).toBeInTheDocument();
    const [observation] = await db.observations.toArray();
    const assessments = await db.assessments.toArray();
    expect(observation).toMatchObject({ healthStatus: 'concern', captureSource: 'gallery' });
    expect(assessments).toHaveLength(1);
    expect(observation!.latestAssessmentId).toBe(assessments[0]!.id);
    expect(assessments[0]).toMatchObject({ provider: 'demo', observationId: observation!.id });
  });

  it('creates a new plant from the result with the AI name stored as an unverified suggestion', async () => {
    await readyModel();
    const { user } = await renderApp('/scan');
    await analyseLeaf(user);
    await user.click(screen.getByRole('radio', { name: /create a new plant/i }));
    expect(screen.getByLabelText('Plant name')).toHaveValue('Tomato');
    await user.click(screen.getByRole('button', { name: /save observation/i }));
    await screen.findByRole('heading', { name: /observation saved/i });
    const [plant] = await db.plants.toArray();
    expect(plant).toMatchObject({ name: 'Tomato', identificationStatus: 'model-suggested' });
    expect((await db.observations.toArray())[0]!.plantId).toBe(plant!.id);
    expect(screen.getByRole('link', { name: /open plant timeline/i })).toHaveAttribute('href', `/garden/${plant!.id}/timeline`);
  });

  it('pre-selects the plant passed in the URL', async () => {
    const plant = await createPlant({ name: 'Balcony basil' });
    await readyModel();
    const { user } = await renderApp(`/scan?plantId=${plant.id}`);
    expect(await screen.findByRole('heading', { name: /scan balcony basil/i })).toBeInTheDocument();
    await analyseLeaf(user);
    expect(screen.getByRole('radio', { name: /add to an existing plant/i })).toBeChecked();
    await user.click(screen.getByRole('button', { name: /save observation/i }));
    await screen.findByRole('heading', { name: /observation saved/i });
    expect((await db.observations.toArray())[0]!.plantId).toBe(plant.id);
  });

  it('never creates duplicates from repeated save taps', async () => {
    await readyModel();
    const { user } = await renderApp('/scan');
    await analyseLeaf(user);
    const save = screen.getByRole('button', { name: /save observation/i });
    await Promise.all([user.click(save), user.click(save), user.click(save)]);
    await screen.findByRole('heading', { name: /observation saved/i });
    expect(await db.observations.count()).toBe(1);
    expect(await db.assessments.count()).toBe(1);
  });

  it('keeps the result and explains the problem when saving fails (quota), then retries', async () => {
    await readyModel();
    const { user } = await renderApp('/scan');
    await analyseLeaf(user);
    const add = vi.spyOn(db.observations, 'add').mockRejectedValueOnce(new DOMException('full', 'QuotaExceededError'));
    await user.click(screen.getByRole('button', { name: /save observation/i }));
    expect(await screen.findByRole('alert')).toHaveTextContent(/not enough storage space/i);
    expect(screen.getByText('What the model observed')).toBeInTheDocument();
    expect(await db.assessments.count()).toBe(0); // rolled back together with the observation
    add.mockRestore();
    await user.click(screen.getByRole('button', { name: /save observation/i }));
    await screen.findByRole('heading', { name: /observation saved/i });
    expect(await db.observations.count()).toBe(1);
  });

  it('shows a coded error and keeps the photo when inference fails', async () => {
    await readyModel();
    testProvider.current.analyze = async () => {
      throw new ModelRuntimeError({ code: 'OUT_OF_MEMORY', message: 'Your device ran out of memory while running the model.' });
    };
    const { user } = await renderApp('/scan');
    await user.upload(await screen.findByTestId('photo-input'), leaf());
    await user.click(await screen.findByRole('button', { name: /analyse on this device/i }));
    const alert = await screen.findByRole('alert');
    expect(alert).toHaveTextContent(/ran out of memory/i);
    expect(alert).toHaveTextContent('OUT_OF_MEMORY');
    expect(screen.getByRole('img', { name: /selected leaf photo/i })).toBeInTheDocument();
    expect(await db.observations.count()).toBe(0);
  });

  it('rejects files that are not images', async () => {
    const { user } = await renderApp('/scan');
    const fake = new File([readFileSync('tests/fixtures/not-an-image.jpg')], 'fake.jpg', { type: 'image/jpeg' });
    await user.upload(await screen.findByTestId('photo-input'), fake);
    const alert = await screen.findByRole('alert');
    expect(alert).toHaveTextContent(/does not look like a photo/i);
    expect(alert).toHaveTextContent('INVALID_IMAGE');
  });

  it('explains camera permission denial and keeps the upload option', async () => {
    Object.defineProperty(navigator, 'mediaDevices', {
      configurable: true,
      value: { getUserMedia: vi.fn().mockRejectedValue(new DOMException('denied', 'NotAllowedError')) },
    });
    const { user } = await renderApp('/scan');
    await user.click(await screen.findByRole('button', { name: /take photo/i }));
    await waitFor(() => expect(screen.getByRole('alert')).toHaveTextContent(/camera permission was denied/i));
    expect(screen.getByRole('button', { name: /choose photo/i })).toBeEnabled();
  });

  it('explains when the camera API is unavailable', async () => {
    const { user } = await renderApp('/scan');
    await user.click(await screen.findByRole('button', { name: /take photo/i }));
    await waitFor(() => expect(screen.getByRole('alert')).toHaveTextContent(/not supported in this browser/i));
  });
});
